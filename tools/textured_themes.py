#!/usr/bin/env python3
"""Generates the three textured bundled themes into ui/public/themes:

  kaya    a pale straight-grained board, matte slate black stones, clam-shell white stones
  walnut  a mid-brown walnut board, matte black and white stones
  yunzi   a bamboo board, yunzi stones (a green rim on the black, a warm white)

Each folder gets board.jpg (a 1600 x 1600 tile that repeats without a seam), black0-3.png and
white0-7.png (160 x 160): the program draws <name>1, <name>2 ... beside <name>0 as other pictures
of the same stone. theme.txt takes ui/public/themes/java-classic/theme.txt with these images.

The boards come from Poly Haven veneer diffuse maps (CC0, by Jenelle van Heerden): ash_veneer,
walnut_veneer and bamboo_veneer, at 2k. Their lighting is flattened and their grain recoloured.
The stones are computed here from a lighting model; no outside picture is used for them. The same
sources and Pillow build reproduce the committed files; each file carries a comment naming this
origin. Needs Pillow.

    python3 tools/textured_themes.py [folder holding <name>_diff_2k.jpg]

Without a folder the sources are downloaded from Poly Haven.
"""
import io
import json
import math
import random
import sys
import urllib.request
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter
from PIL.PngImagePlugin import PngInfo

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "ui" / "public" / "themes"
TEMPLATE = OUT / "java-classic" / "theme.txt"
PH = "https://dl.polyhaven.org/file/ph-assets/Textures/jpg/2k/{0}/{0}_diff_2k.jpg"
NOTE = "Generated by tools/textured_themes.py"
BOARD = 1600  # board texture tile, px
STONE = 160  # stone image, px
SS = 2  # supersampling

# Light from the upper left, viewer straight above (screen y grows downwards).
_L = (-0.45, -0.55, 0.70)
_n = math.sqrt(sum(c * c for c in _L))
L = tuple(c / _n for c in _L)
H = (L[0], L[1], L[2] + 1)
_n = math.sqrt(sum(c * c for c in H))
H = tuple(c / _n for c in H)

THEMES = {
    "kaya": {
        "board": ("ash_veneer", True, (226, 188, 122), 0.55, 0.12),
        "black": dict(albedo=(22, 22, 24), s=0.42, p=2.0, amb=0.55, kd=0.45, broad=0.13, sharp=0.06, shine=22,
                      spec=(255, 255, 255), mottle=0.05),
        "white": dict(albedo=(238, 234, 224), s=0.42, p=2.0, amb=0.62, kd=0.42, broad=0.06, sharp=0.22, shine=34,
                      spec=(255, 255, 250), clam=True, mottle=0.02),
    },
    "walnut": {
        "board": ("walnut_veneer", False, (136, 98, 68), 0.9, 0.25),
        "black": dict(albedo=(36, 35, 34), s=0.38, p=2.2, amb=0.6, kd=0.4, broad=0.10, sharp=0.02, shine=12,
                      spec=(255, 250, 240), mottle=0.08),
        "white": dict(albedo=(228, 225, 218), s=0.38, p=2.2, amb=0.62, kd=0.40, broad=0.05, sharp=0.03, shine=12,
                      spec=(255, 250, 240), mottle=0.02, speckle=True),
    },
    "yunzi": {
        "board": ("bamboo_veneer", True, (230, 201, 143), 0.9, 0.20),
        "black": dict(albedo=(16, 20, 18), s=0.32, p=2.5, amb=0.55, kd=0.40, broad=0.14, sharp=0.30, shine=45,
                      spec=(210, 230, 215), mottle=0.04, rim=(10, 32, 20)),
        "white": dict(albedo=(238, 233, 207), s=0.32, p=2.5, amb=0.68, kd=0.34, broad=0.06, sharp=0.18, shine=28,
                      spec=(255, 253, 235), mottle=0.035),
    },
}
VARIANTS = {"black": 4, "white": 8}


class Noise:
    """2-D value noise with smooth interpolation, repeatable from `seed`."""

    def __init__(self, seed):
        rnd = random.Random(seed)
        self.perm = list(range(256))
        rnd.shuffle(self.perm)
        self.perm += self.perm
        self.val = [rnd.random() for _ in range(256)]

    def _v(self, x, y):
        return self.val[self.perm[(self.perm[x & 255] + y) & 255]]

    def __call__(self, x, y):
        x0, y0 = math.floor(x), math.floor(y)
        fx, fy = x - x0, y - y0
        ux, uy = fx * fx * (3 - 2 * fx), fy * fy * (3 - 2 * fy)
        a, b = self._v(x0, y0), self._v(x0 + 1, y0)
        c, d = self._v(x0, y0 + 1), self._v(x0 + 1, y0 + 1)
        return (a + (b - a) * ux) + ((c + (d - c) * ux) - (a + (b - a) * ux)) * uy

    def fbm(self, x, y, octaves=3):
        total, amp, f, norm = 0.0, 1.0, 1.0, 0.0
        for _ in range(octaves):
            total += amp * self(x * f, y * f)
            norm += amp
            amp *= 0.5
            f *= 2.0
        return total / norm


def stone(look, seed):
    rnd = random.Random(seed)
    noise = Noise(seed)
    size = STONE * SS
    img = Image.new("RGBA", (size, size))
    px = img.load()
    s, p = look["s"], look["p"]
    # Clam stripes: growth arcs around a centre far off the stone, a different one per variant.
    ang = rnd.uniform(0, 2 * math.pi)
    dist = rnd.uniform(2.5, 5.0)
    cx, cy = math.cos(ang) * dist, math.sin(ang) * dist
    freq = rnd.uniform(6, 9)
    tint = 1 + rnd.uniform(-0.012, 0.012)
    half = size / 2
    for j in range(size):
        y = (j + 0.5 - half) / half
        for i in range(size):
            x = (i + 0.5 - half) / half
            rho2 = x * x + y * y
            if rho2 >= 1:
                continue
            rho = math.sqrt(rho2)
            if rho < 1e-6:
                nx = ny = 0.0
            else:
                rp = min(rho ** p, 0.9995)
                slope = s * rho ** (p - 1) * (1 - rp) ** (1 / p - 1)
                slope = min(slope, 12.0)
                nx, ny = slope * x / rho, slope * y / rho
            nz = 1.0
            n = math.sqrt(nx * nx + ny * ny + 1)
            nx, ny, nz = nx / n, ny / n, nz / n
            diff = max(0.0, nx * L[0] + ny * L[1] + nz * L[2])
            nh = max(0.0, nx * H[0] + ny * H[1] + nz * H[2])
            spec = look["broad"] * nh ** 6 + look["sharp"] * nh ** look["shine"]
            a = 1 - look["mottle"] * (noise.fbm(x * 3 + 7, y * 3 + 3) - 0.5) * 2
            if look.get("clam"):
                d = math.hypot(x - cx, y - cy)
                phase = d * freq + 0.35 * noise.fbm(x * 2.5, y * 2.5)
                broad = 0.5 + 0.5 * math.cos(2 * math.pi * phase * 0.33)
                fine = (0.5 + 0.5 * math.cos(2 * math.pi * phase * 1.6)) ** 6
                a *= 1 - 0.03 * broad - 0.018 * fine
            if look.get("speckle"):
                a *= 1 - 0.06 * max(0.0, noise(x * 40 + 11, y * 40 + 5) - 0.75) * 4
            a *= tint
            light = look["amb"] + look["kd"] * diff
            col = []
            for k in range(3):
                v = look["albedo"][k] * a * light + look["spec"][k] * spec
                if look.get("rim"):
                    # Light passing through the thin edge on the side away from the light.
                    back = max(0.0, -(x * L[0] + y * L[1]) / max(rho, 1e-6)) * max(0.0, rho - 0.78) / 0.22
                    v += look["rim"][k] * back
                col.append(max(0, min(255, int(v + 0.5))))
            px[i, j] = (col[0], col[1], col[2], 255)
    return img.resize((STONE, STONE), Image.LANCZOS)


def source(name, folder):
    if folder:
        return Image.open(Path(folder) / f"{name}_diff_2k.jpg")
    return Image.open(io.BytesIO(urllib.request.urlopen(PH.format(name)).read()))


def tiled(image):
    w, h = image.size
    sheet = Image.new(image.mode, (w * 3, h * 3))
    for ty in range(3):
        for tx in range(3):
            sheet.paste(image, (tx * w, ty * h))
    return sheet


def board(name, rotate, colour, contrast, keep, folder):
    """The veneer's grain on `colour`: its lighting flattened to `keep` of its broad variation."""
    grey = source(name, folder).convert("L")
    if rotate:
        grey = grey.transpose(Image.Transpose.ROTATE_90)
    grey = grey.resize((BOARD, BOARD), Image.LANCZOS)
    box = (BOARD, BOARD, BOARD * 2, BOARD * 2)
    broad = tiled(grey).filter(ImageFilter.GaussianBlur(BOARD / 24)).crop(box)
    mean = sum(i * c for i, c in enumerate(grey.histogram())) / (BOARD * BOARD)
    broad = broad.point(lambda v: int(v * (1 - keep) + mean * keep + 0.5))
    detail = ImageChops.subtract(grey, broad, scale=1, offset=128)
    chans = [detail.point(lambda v, c=c: max(0, min(255, int(c * (1 + contrast * (v - 128) / 128) + 0.5))))
             for c in colour]
    return Image.merge("RGB", chans)


def build(folder):
    template = json.loads(TEMPLATE.read_text())
    for index, (theme, spec) in enumerate(THEMES.items()):
        out = OUT / theme
        out.mkdir(parents=True, exist_ok=True)
        note = f"{NOTE} ({spec['board'][0]}, Poly Haven, CC0)"
        board(*spec["board"], folder).save(out / "board.jpg", quality=88, optimize=True, comment=note)
        info = PngInfo()
        info.add_text("Comment", NOTE)
        for colour, count in VARIANTS.items():
            for v in range(count):
                seed = index * 1000 + (colour == "white") * 100 + v
                stone(spec[colour], seed).save(out / f"{colour}{v}.png", optimize=True, pnginfo=info)
        values = dict(template, **{"board-image": "board.jpg", "black-stone-image": "black0.png", "white-stone-image": "white0.png"})
        (out / "theme.txt").write_text(json.dumps(values, indent=2, ensure_ascii=False) + "\n")
        print(theme, "done")


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else None)
