let lang: Exclude<Language, "System"> = "ZhCn";

/** The document language of each interface language, so the system font picks that language's
 *  glyphs (Chinese, Japanese and Korean share code points). */
const DOCUMENT_LANGUAGE: Record<Exclude<Language, "System">, string> = { ZhCn: "zh-CN", ZhTw: "zh-TW", EnUs: "en", JaJp: "ja", KoKr: "ko", ThTh: "th" };

/** Sets the language of the texts and of the document. */
export function setLanguage(l: Language): void {
  lang = l === "System" ? "ZhCn" : l;
  document.documentElement.lang = DOCUMENT_LANGUAGE[lang];
}

export function language(): Language {
  return lang;
}

/** Java `Lizzie.isChinese` (bundle value "yes"). */
export function isChinese(): boolean {
  return t("Lizzie.isChinese") === "yes";
}

/** Java resource string, or this product's resource key; unknown keys are shown literally (Java
 *  uses literal text for some items). */
export function t(key: string): string {
  return JAVA[lang]?.[key] ?? PRODUCT_KEYS[lang]?.[key] ?? JAVA.ZhCn?.[key] ?? key;
}

/** MessageFormat-style `{0}` substitution; `{0,number,integer}` rounds and groups the digits like
 *  Java's integer NumberFormat (every UI locale groups with ","). */
export function format(text: string, ...args: (string | number)[]): string {
  return text.replace(/\{(\d+)(,number,integer)?\}/g, (_, k, integer) => {
    const arg = args[Number(k)];
    if (integer && typeof arg === "number") return Math.round(arg).toLocaleString("en-US");
    return `${arg ?? ""}`;
  });
}

/** Product-only messages of a feature module, kept next to that feature: one table per interface
 *  language, each with the same keys, so a message missing in one language fails the type check.
 *  Later registrations do not replace existing keys. */
export function registerProduct<K extends string>(tables: Record<Exclude<Language, "System">, Record<K, string>>): void {
  for (const [language, table] of Object.entries(tables)) {
    PRODUCT[language] = { ...table, ...PRODUCT[language] };
  }
}

export function product(key: string, ...args: (string | number)[]): string {
  const table = PRODUCT[lang] ?? PRODUCT.EnUs;
  return format(table[key] ?? PRODUCT.EnUs[key] ?? key, ...args);
}
