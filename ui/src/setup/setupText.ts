export function size(bytes: number | bigint | null | undefined): string {
  if (bytes == null) return product("setupUnknown"); const n = Number(bytes); return n >= 1024 ** 3 ? `${(n / 1024 ** 3).toFixed(2)} GB` : `${(n / 1024 ** 2).toFixed(1)} MB`;
}
